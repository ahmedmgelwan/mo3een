from pydantic import BaseModel, Field


class AskRequest(BaseModel):
    question: str = Field(
        ..., description="The question to ask the model.", min_length=1, max_length=1000
    )


class AskResponse(BaseModel):
    answer: str = Field(
        ...,
        description="The answer generated by the model.",
        min_length=1,
        max_length=10000,
    )
    latency_ms: int = Field(
        ..., description="The time taken to generate the answer in milliseconds.", gt=0
    )
    usage: dict = Field(
        ..., description="Token usage statistics for the request and response."
    )
